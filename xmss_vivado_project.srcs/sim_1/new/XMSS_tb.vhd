    signal sig_memory : ram_type := init_bram;
    signal mem_pending : std_logic := '0';
    signal mem_addr_lat : std_logic_vector(31 downto 0) := (others => '0');

begin

    sig_base <= SIG_BASE_C;
    pk_base  <= PK_BASE_C;
    msg_base <= MSG_BASE_C;
    mem_gnt  <= '1'; -- El bus siempre acepta la petición inmediatamente

    -- Instancia del Wrapper (Device Under Test)
    uut : entity work.XMSS
        port map (
            clk         => clk,
            reset       => reset,
            enable      => enable,
            mlen        => mlen,
            sig_base    => sig_base,
            msg_base    => msg_base,
            pk_base     => pk_base,
            done        => done,
            valid       => valid,
            
            mem_req     => mem_req,
            mem_addr    => mem_addr,
            mem_gnt     => mem_gnt,
            mem_rvalid  => mem_rvalid,
            mem_rdata   => mem_rdata
        );

    -- Generador de Reloj
    process
    begin
        clk <= '1'; wait for clk_period / 2;
        clk <= '0'; wait for clk_period / 2;
    end process;

    -- Emulador de Memoria Externa (Lectura 256-bit por DMA)
    process(clk)
        variable addr_u : unsigned(31 downto 0);
        variable idx : integer;
    begin
        if rising_edge(clk) then
            mem_rvalid <= '0';

            if mem_pending = '1' then
                addr_u := unsigned(mem_addr_lat);
                
                -- RUTEO SEGÚN MAPA DE MEMORIA DE X-HEEP
        if addr_u >= unsigned(MSG_BASE_C) then
            idx := to_integer(shift_right(addr_u - unsigned(MSG_BASE_C), 5));
            mem_rdata <= sig_memory(BRAM_MESSAGE + idx); -- <--- LECTURA CORREGIDA
            
        elsif addr_u >= unsigned(PK_BASE_C) then
            idx := to_integer(shift_right(addr_u - unsigned(PK_BASE_C), 5));
            if idx = 0 then
                mem_rdata <= PK_ROOT;
            elsif idx = 1 then
                mem_rdata <= PUB_SEED;
            else
                mem_rdata <= (others => '0');
            end if;
            
        else
            idx := to_integer(shift_right(addr_u - unsigned(SIG_BASE_C), 5));
            mem_rdata <= sig_memory(idx);
        end if;
                
                mem_rvalid <= '1';
                mem_pending <= '0';
            end if;

            if mem_req = '1' then
                mem_addr_lat <= mem_addr;
                mem_pending <= '1';
            end if;
        end if;
    end process;

    -- Secuencia de Estímulos y Verificación
    process
    begin
        -- Condiciones iniciales
        reset <= '1';
        enable <= '0';
        -- El tamaño de "Firma TFG VHDL" es de 14 bytes = 112 bits
        mlen <= std_logic_vector(to_unsigned(8*33752, 32)); 
        
        wait for 50 ns;
        wait until rising_edge(clk);
        reset <= '0';
        wait for 50 ns;

        report "===========================================================" severity note;
        report "=== INICIANDO VERIFICACION EN EL TOP (XMSS DMA)         ===" severity note;
        report "===========================================================" severity note;

        wait until rising_edge(clk);
        enable <= '1'; -- Simulamos que el procesador (Boot ROM) arranca el hardware

        -- Esperar a que el hardware orqueste todas las lecturas de memoria y finalice
        wait until done = '1';
        
        report " " severity note;
        report "=== VERIFICACION FINALIZADA ===" severity note;

        -- Comprobación del resultado
        if valid = STATUS_VALID then
            report "    [PASS] FIRMA VALIDA. EL HARDWARE LEYO Y VERIFICO CORRECTAMENTE LA FIRMA." severity note;
        else
            report "    [FAIL] RESULTADO DE LA FIRMA: INVALIDA." severity error;
        end if;
        report "===========================================================" severity note;

        -- Handshake: el procesador lee el resultado y da acuse de recibo bajando el enable
        wait for clk_period;
        enable <= '0';

        -- Comprobamos si la máquina de estados obedece y baja los flags
        wait for 4 * clk_period;
        if valid = STATUS_IDLE and done = '0' then
            report "    [INFO] Top Level reseteado y en reposo correctamente." severity note;
        else
            report "    [FAIL] El Top Level no limpio las senales despues de bajar enable." severity error;
        end if;
        
        wait;
    end process;

end Behavioral;